#!/usr/bin/env node
// Builds the "MCPBridge" embedded module from dexmcp/lua/*.lua and injects it into dexplusplus.lua.
// Idempotent: re-running replaces the previously injected block (between the MCPBRIDGE markers).
//
//   node scripts/embed.js [path/to/dexplusplus.lua]
//   node scripts/embed.js --print        # print the generated module instead of patching
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const luaDir = path.join(here, "..", "lua");
const args = process.argv.slice(2);
const printOnly = args.includes("--print");
const target = path.resolve(args.find((a) => !a.startsWith("--")) ?? path.join(here, "..", "..", "dexplusplus.lua"));

const BEGIN = "--[[MCPBRIDGE:BEGIN]]";
const END = "--[[MCPBRIDGE:END]]";

export function buildModule() {
	const files = fs.readdirSync(luaDir).filter((f) => f.endsWith(".lua")).sort();
	const parts = files.map((f) => {
		const name = f.replace(/\.lua$/, "");
		const body = fs.readFileSync(path.join(luaDir, f), "utf8").replace(/\r\n/g, "\n");
		return `PARTS[#PARTS + 1] = {"${name}", function(B)\n${body}\nend}\n`;
	});

	return `${BEGIN}
["MCPBridge"] = function()
--[[
	MCP Bridge Module  (GENERATED by dexmcp/scripts/embed.js - edit dexmcp/lua/*.lua instead)

	Connects Dex++ to an MCP server (dexmcp/server) over WebSocket (or HTTP long-poll fallback)
	so an MCP client can drive this Roblox client: explorer, properties, scripts, remotes, GC, hooks...
]]

-- Common Locals
local Main,Lib,Apps,Settings -- Main Containers
local Explorer, Properties, ScriptViewer, Notebook -- Major Apps
local API,RMD,env,service,plr,create,createSimple -- Main Locals

local function initDeps(data)
	Main = data.Main
	Lib = data.Lib
	Apps = data.Apps
	Settings = data.Settings

	API = data.API
	RMD = data.RMD
	env = data.env
	service = data.service
	plr = data.plr
	create = data.create
	createSimple = data.createSimple
end

local function initAfterMain()
	Explorer = Apps.Explorer
	Properties = Apps.Properties
	ScriptViewer = Apps.ScriptViewer
	Notebook = Apps.Notebook
end

local PARTS = {}

${parts.join("\n")}
local function main()
	local MCP = {}

	local Dex = {
		Main = Main, Lib = Lib, Apps = Apps, Settings = Settings,
		API = API, RMD = RMD, env = env, service = service, plr = plr,
		getSelection = function() return selection end,
		getNodes = function() return nodes end,
	}
	local B = {Dex = Dex, H = {}, cfg = Settings.MCP, partErrors = {}}
	MCP.Bridge = B

	for _, part in ipairs(PARTS) do
		local ok, err = pcall(part[2], B)
		if not ok then
			B.partErrors[#B.partErrors + 1] = part[1] .. ": " .. tostring(err)
			warn("[Dex++ MCP] part '" .. part[1] .. "' failed to load: " .. tostring(err))
		end
	end

	MCP.Init = function()
		local window = Lib.Window.new()
		window:SetTitle("MCP")
		window:Resize(290, 190)
		MCP.Window = window

		if B.startCaptures then pcall(B.startCaptures) end
		if B.buildUI then
			local ok, err = pcall(B.buildUI, window)
			if not ok then warn("[Dex++ MCP] UI failed: " .. tostring(err)) end
		end
		if B.T and Settings.MCP.AutoConnect then B.T.start() end
	end

	return MCP
end

return {InitDeps = initDeps, InitAfterMain = initAfterMain, Main = main}
end,
${END}
`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);

function patch() {
if (printOnly) {
	process.stdout.write(buildModule());
	return;
}

let src = fs.readFileSync(target, "utf8");
const crlf = src.includes("\r\n");
src = src.replace(/\r\n/g, "\n");

let block = buildModule();

const hasBlock = src.includes(BEGIN) && src.includes(END);
if (hasBlock) {
	const a = src.indexOf(BEGIN);
	const b = src.indexOf(END) + END.length;
	src = src.slice(0, a) + block.trimEnd() + src.slice(b);
} else {
	// inject right before the end of the EmbeddedModules table
	const anchor = /\n\}\nlocal oldgame = oldgame or game\n/;
	if (!anchor.test(src)) {
		console.error("could not find the end of EmbeddedModules in " + target);
		process.exit(1);
	}
	src = src.replace(anchor, (m) => "\n" + block.trimEnd() + m);
}

if (crlf) src = src.replace(/\n/g, "\r\n");
fs.writeFileSync(target, src);
console.log(`${hasBlock ? "updated" : "injected"} MCPBridge into ${target} (${(src.length / 1024).toFixed(0)} KB)`);
}

if (isMain) patch();
