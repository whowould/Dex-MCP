#!/usr/bin/env node
// Generates TOOLS.md (the full tool catalogue) from the tool definitions.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildTools } from "../server/tools/index.js";
import { z } from "zod";

const here = path.dirname(fileURLToPath(import.meta.url));
const defs = buildTools({ bridge: {}, toolCount: () => 0 });

function describeParam(schema) {
	let s = schema;
	let optional = false;
	for (;;) {
		const t = s?._zod?.def?.type;
		if (t === "optional" || t === "nullable") {
			optional = true;
			s = s._zod.def.innerType;
		} else break;
	}
	const def = s?._zod?.def ?? {};
	let type = def.type ?? "any";
	if (type === "enum") type = Object.values(def.entries ?? {}).map((v) => JSON.stringify(v)).join(" \\| ");
	else if (type === "union") type = (def.options ?? []).map((o) => o?._zod?.def?.type ?? "any").join(" \\| ");
	else if (type === "array") type = `${def.element?._zod?.def?.type ?? "any"}[]`;
	return { optional, type, desc: schema.description ?? s?.description ?? "" };
}

const groups = new Map();
for (const d of defs) {
	if (!groups.has(d.group)) groups.set(d.group, []);
	groups.get(d.group).push(d);
}

let out = `# Dex++ MCP tool catalogue\n\n${defs.length} tools. Generated by \`npm run docs\` - do not edit by hand.\n\n`;
out += "Every tool also accepts an optional `client` argument to target a specific connected game client.\n\n";
for (const [group, list] of groups) {
	out += `## ${group} (${list.length})\n\n`;
	for (const d of list) {
		out += `### \`${d.name}\`\n\n${d.description}\n\n`;
		const keys = Object.keys(d.shape);
		if (keys.length) {
			out += "| parameter | type | description |\n|---|---|---|\n";
			for (const k of keys) {
				const { optional, type, desc } = describeParam(d.shape[k]);
				out += `| \`${k}\`${optional ? "" : " **(required)**"} | ${type} | ${desc.replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 400)} |\n`;
			}
			out += "\n";
		}
	}
}
const file = path.join(here, "..", "TOOLS.md");
fs.writeFileSync(file, out);
console.log(`wrote ${file} (${defs.length} tools)`);
